-- Reglas de paso del MER al modelo relacional que se aplicaron:
--   * Cada entidad -> una tabla con PK BIGINT autoincrementable.
--   * Generalización Usuario (d, total) -> tabla padre "usuario" y tablas
--     hijas "agricultor" y "comprador" que comparten la PK (PK = FK).
--   * Atributo compuesto nombre_completo -> columnas nombres, apellidos.
--   * Atributo multivaluado telefono -> tabla aparte usuario_telefono (1FN).
--   * Atributos derivados (promedio_calificacion, total del pedido) NO se
--     guardan: se calculan con consultas (evita redundancia, 3FN).
--   * Relaciones 1:N -> FK en la tabla del lado N.
--   * Relaciones 1:1 -> FK con restricción UNIQUE.
--   * Relaciones N:M con atributos (incluye, contacta) -> tabla propia:
--     detalle_pedido y mensaje_contacto.
-- =====================================================================

-- ---------- Catálogos ----------
CREATE TABLE municipio (
    id_municipio  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE categoria (
    id_categoria  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(60) NOT NULL UNIQUE
);

-- ---------- Usuarios (generalización) ----------
CREATE TABLE usuario (
    id_usuario       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres          VARCHAR(80)  NOT NULL,
    apellidos        VARCHAR(80)  NOT NULL,
    correo           VARCHAR(120) NOT NULL UNIQUE,
    contrasena_hash  VARCHAR(255) NOT NULL,          -- BCrypt, nunca texto plano
    rol              VARCHAR(15)  NOT NULL CHECK (rol IN ('AGRICULTOR', 'COMPRADOR')),
    fecha_registro   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE usuario_telefono (
    id_usuario  BIGINT      NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    telefono    VARCHAR(20) NOT NULL,
    PRIMARY KEY (id_usuario, telefono)
);

CREATE TABLE agricultor (
    id_usuario  BIGINT      PRIMARY KEY REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    cedula      VARCHAR(15) NOT NULL UNIQUE
);

CREATE TABLE comprador (
    id_usuario      BIGINT      PRIMARY KEY REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    documento       VARCHAR(20) NOT NULL UNIQUE,
    tipo_comprador  VARCHAR(15) NOT NULL
                    CHECK (tipo_comprador IN ('INDIVIDUAL', 'COMERCIANTE', 'RESTAURANTE'))
);

-- ---------- Oferta agrícola ----------
CREATE TABLE finca (
    id_finca        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100)  NOT NULL,
    vereda          VARCHAR(100),
    area_hectareas  NUMERIC(10,2) CHECK (area_hectareas > 0),
    id_agricultor   BIGINT NOT NULL REFERENCES agricultor (id_usuario),
    id_municipio    BIGINT NOT NULL REFERENCES municipio (id_municipio)
);

CREATE TABLE producto (
    id_producto          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                 VARCHAR(80)   NOT NULL,
    cantidad_disponible  NUMERIC(12,2) NOT NULL CHECK (cantidad_disponible >= 0),
    precio_unitario      NUMERIC(12,2) NOT NULL CHECK (precio_unitario > 0),
    fecha_cosecha        DATE          NOT NULL,
    estado               VARCHAR(15)   NOT NULL DEFAULT 'ACTIVO'
                         CHECK (estado IN ('ACTIVO', 'AGOTADO', 'INACTIVO')),
    id_finca             BIGINT NOT NULL REFERENCES finca (id_finca),
    id_categoria         BIGINT NOT NULL REFERENCES categoria (id_categoria)
);

-- N:M "contacta" (HU-05)
CREATE TABLE mensaje_contacto (
    id_mensaje    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comprador  BIGINT NOT NULL REFERENCES comprador (id_usuario),
    id_producto   BIGINT NOT NULL REFERENCES producto (id_producto),
    mensaje       TEXT      NOT NULL,
    fecha_envio   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- Compra ----------
CREATE TABLE pedido (
    id_pedido     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comprador  BIGINT    NOT NULL REFERENCES comprador (id_usuario),
    fecha_pedido  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado        VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE_PAGO'
                  CHECK (estado IN ('PENDIENTE_PAGO', 'PAGADO', 'ALISTADO',
                                    'EN_CAMINO', 'ENTREGADO', 'CANCELADO'))
);

-- N:M "incluye" (HU-08, HU-12)
CREATE TABLE detalle_pedido (
    id_pedido        BIGINT        NOT NULL REFERENCES pedido (id_pedido) ON DELETE CASCADE,
    id_producto      BIGINT        NOT NULL REFERENCES producto (id_producto),
    cantidad         NUMERIC(12,2) NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(12,2) NOT NULL CHECK (precio_unitario > 0), -- precio al momento de la compra
    PRIMARY KEY (id_pedido, id_producto)
);

-- 1:1 "genera" (HU-07, HU-11)
CREATE TABLE pago (
    id_pago     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido   BIGINT        NOT NULL UNIQUE REFERENCES pedido (id_pedido),
    metodo      VARCHAR(30)   NOT NULL,
    monto       NUMERIC(14,2) NOT NULL CHECK (monto > 0),
    estado      VARCHAR(15)   NOT NULL CHECK (estado IN ('APROBADO', 'RECHAZADO')),
    fecha_pago  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 1:1 "requiere" (HU-06, HU-13)
CREATE TABLE envio (
    id_envio            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido           BIGINT      NOT NULL UNIQUE REFERENCES pedido (id_pedido),
    codigo_seguimiento  VARCHAR(30) NOT NULL UNIQUE,
    fecha_salida        TIMESTAMP   NOT NULL,
    origen              VARCHAR(120) NOT NULL,
    destino             VARCHAR(120) NOT NULL,
    eta                 TIMESTAMP,
    estado              VARCHAR(15) NOT NULL DEFAULT 'EN_CAMINO'
                        CHECK (estado IN ('EN_CAMINO', 'ENTREGADO'))
);

-- 1:N "recibe" (HU-09, HU-10): máximo una calificación de cada tipo por pedido
CREATE TABLE calificacion (
    id_calificacion  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido        BIGINT     NOT NULL REFERENCES pedido (id_pedido),
    tipo             VARCHAR(12) NOT NULL CHECK (tipo IN ('PRODUCTO', 'TRANSPORTE')),
    estrellas        SMALLINT   NOT NULL CHECK (estrellas BETWEEN 1 AND 5),
    comentario       TEXT,
    fecha            TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_pedido, tipo)
);

-- ---------- Índices para consultas frecuentes ----------
CREATE INDEX idx_producto_categoria ON producto (id_categoria);
CREATE INDEX idx_finca_municipio    ON finca (id_municipio);   -- filtro HU-04
CREATE INDEX idx_pedido_comprador   ON pedido (id_comprador);

